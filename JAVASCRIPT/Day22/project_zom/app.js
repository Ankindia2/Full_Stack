function getrestaurant(restaurants) {

    const root = document.getElementById('root');
    root.replaceChildren();

    restaurants.forEach(restaurant => {

        /* CARD */
        const card = document.createElement('div');
        card.classList.add('card');

        /* IMAGE */
        const image = document.createElement("img");
        image.src = `images/${restaurant.image}.jpeg`;
        image.alt = restaurant.name;

        /* CARD CONTENT */
        const card_content = document.createElement('div');
        card_content.classList.add('card_content');

        /* CARD HEADER */
        const card_header = document.createElement('div');
        card_header.classList.add('card_header');

        const h3 = document.createElement('h3');
        h3.textContent = restaurant.name;

        const rate = document.createElement('span');
        rate.textContent = "Rating: " + restaurant.rating;
        rate.classList.add('rating');

        card_header.append(h3, rate);

        /* CARD FOOTER */
        const card_footer = document.createElement('div');
        card_footer.classList.add('card_footer');

        const food = document.createElement('div');
        food.textContent = restaurant.foodTypes;

        const price = document.createElement('span');
        price.textContent = "₹" + restaurant.price_for_two;

        card_footer.append(food, price);

        /* CARD LOCATION */
        const card_location = document.createElement('div');
        card_location.classList.add('card_location');

        const location = document.createElement('span');
        location.textContent = restaurant.location;

        // ✅ FIXED DISTANCE
        const distanceValue = Number(
            restaurant.distance_from_customer_house
        );

        const distance = document.createElement('span');
        distance.textContent = isNaN(distanceValue)
            ? "N/A"
            : distanceValue + " km";

        card_location.append(location, distance);

        /* APPEND ALL */
        card_content.append(card_header, card_footer, card_location);
        card.append(image, card_content);
        root.append(card);
    });
}

/* INITIAL LOAD */
getrestaurant(restaurants);

/* FILTER: ALCOHOL */
document.getElementById("alcohol").addEventListener('click', () => {
    const result = restaurants.filter(r => r.alchol === true);
    getrestaurant(result);
});

/* FILTER: RATING */
document.getElementById("rating").addEventListener('click', () => {
    const result = restaurants.filter(r => r.rating > 4.5);
    getrestaurant(result);
});

/* OPEN FILTER POPUP */
document.getElementById('filter').addEventListener('click', () => {
    document.getElementById("filteroption").classList.remove("hidden");
});

/* APPLY FILTER */
document.getElementById('applyFiler').addEventListener('click', () => {

    const element = document.querySelector(
        'input[name="filteroption"]:checked'
    );

    if (!element) return;

    const answer = element.value;

    if (answer === "rating") {
        restaurants.sort((a, b) => b.rating - a.rating);
    }
    else if (answer === "highLow") {
        restaurants.sort((a, b) =>
            b.price_for_two - a.price_for_two
        );
    }
    else if (answer === "costLowHigh") {
        restaurants.sort((a, b) =>
            a.price_for_two - b.price_for_two
        );
    }
    else if (answer === "distance") {
        restaurants.sort((a, b) =>
            Number(a.distance_from_customer_house) -
            Number(b.distance_from_customer_house)
        );
    }

    document.getElementById("filteroption")
        .classList.add("hidden");

    getrestaurant(restaurants);
});

/* CLOSE FILTER */
document.getElementById('closeFilter')
    .addEventListener('click', () => {
        document.getElementById("filteroption")
            .classList.add("hidden");
    });
